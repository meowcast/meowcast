#!/usr/bin/env python3
"""Package the UI for the /opt deploy loop (python3 serve.py on the Mac, fetch on the dongle).

package-ui.py BINARY RUNTIME_MANIFEST OUTDIR

Copies the binary, any shared libraries it needs that the initramfs does not already
provide (RUNTIME_MANIFEST is package-gpu.py's list of what is in the initramfs), the fonts
and run.sh into OUTDIR, then writes OUTDIR/SHA256SUMS and OUTDIR/install.sh. On the dongle:
    fetch ui/install.sh && sh /opt/install.sh      # -> /opt/ui, verified
    /opt/ui/run.sh 1080p60                          # or 4k30
"""
from pathlib import Path
import hashlib, json, re, shutil, subprocess, sys

binary, manifest, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
here = Path(__file__).resolve().parent
runtime = json.loads(manifest.read_text())['files']
on_device = {Path(p).name for p in runtime}
search = [Path('/build/mesa-install/usr/lib'), Path('/usr/lib/arm-linux-gnueabihf'),
          Path('/lib/arm-linux-gnueabihf'), Path('/usr/arm-linux-gnueabihf/lib')]

if out.exists():
    shutil.rmtree(out)  # generated directory, rebuilt from scratch every time
(out / 'bin').mkdir(parents=True)

def needed(elf):
    hdr = subprocess.check_output(['arm-linux-gnueabihf-readelf', '-h', str(elf)], text=True)
    if 'ELF32' not in hdr or 'ARM' not in hdr:
        raise SystemExit(f'not a 32-bit ARM ELF: {elf}')
    dyn = subprocess.check_output(['arm-linux-gnueabihf-readelf', '-d', str(elf)], text=True)
    return re.findall(r'\(NEEDED\).*\[([^]]+)\]', dyn)

extra, todo, seen = [], [binary], set()
while todo:
    elf = todo.pop()
    for so in needed(elf):
        if so in seen:
            continue
        seen.add(so)
        if so in on_device:
            continue
        dep = next((p / so for p in search if (p / so).exists()), None)
        if dep is None:
            raise SystemExit(f'missing ARM dependency {so} (needed by {elf.name})')
        extra.append(dep.resolve())
        todo.append(dep.resolve())

# Mesa libraries rebuilt since the initramfs (e.g. with patches/mesa-*.patch) ship in lib/
# and take precedence through LD_LIBRARY_PATH, so driver fixes need no reboot.
mesa = Path('/build/mesa-install/usr/lib')
for path, rec in runtime.items():
    src = mesa / Path(path).name
    if path.startswith('/usr/lib/') and src.exists() and \
            hashlib.sha256(src.read_bytes()).hexdigest() != rec['sha256']:
        extra.append(src.resolve().with_name(Path(path).name) if src.is_symlink() else src)

shutil.copy2(binary, out / 'bin/miracast-ui')
if extra:
    (out / 'lib').mkdir()
    for lib in extra:
        shutil.copy2(lib.resolve(), out / 'lib' / lib.name)
(out / 'fonts').mkdir()
# Latin subsets only (assets/fonts/subset.py); the full faces are store assets, fetched by the
# launcher when some text needs them.
for f in sorted((here / 'assets/fonts/latin').glob('NotoSans-*.ttf')):
    shutil.copy2(f, out / 'fonts' / f.name)
for script in ('run.sh', 'bench.sh', 'scrollbench.sh', 'settingsbench.sh', 'cpuprobe.sh', 'remote-link.sh'):
    shutil.copy2(here / script, out / script)

files = sorted(p.relative_to(out).as_posix() for p in out.rglob('*') if p.is_file())
sums = ''.join(f"{hashlib.sha256((out / f).read_bytes()).hexdigest()}  {f}\n" for f in files)
(out / 'SHA256SUMS').write_text(sums)
dirs = sorted({str(Path(f).parent) for f in files} - {'.'})
install = ['#!/bin/sh', '# Generated by ui/package-ui.py: fetch the UI into /opt/ui and verify it.',
           'rm -rf /opt/ui && mkdir -p ' + ' '.join(['/opt/ui'] + [f'/opt/ui/{d}' for d in dirs]),
           'for f in SHA256SUMS ' + ' '.join(files) + '; do',
           '  fetch "ui/$f" "/opt/ui/$f" >/dev/null || { echo UI_INSTALL_FAIL "$f"; exit 1; }',
           'done',
           'chmod 755 /opt/ui/bin/miracast-ui /opt/ui/run.sh /opt/ui/bench.sh /opt/ui/scrollbench.sh /opt/ui/settingsbench.sh /opt/ui/cpuprobe.sh /opt/ui/remote-link.sh',
           'cd /opt/ui && sha256sum -c -s SHA256SUMS && echo "UI_INSTALL_OK $(du -sk /opt/ui | cut -f1)KiB" || echo UI_INSTALL_BADSUM', '']
(out / 'install.sh').write_text('\n'.join(install))
total = sum((out / f).stat().st_size for f in files)
print(f'UI package: {out} {total} bytes; binary {(out / "bin/miracast-ui").stat().st_size} bytes')
print('NEEDED:', ' '.join(sorted(seen)))
print('extra libs:', ' '.join(p.name for p in extra) or 'none')
